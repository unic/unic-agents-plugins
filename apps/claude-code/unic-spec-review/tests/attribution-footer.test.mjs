import assert from 'node:assert/strict'
import { describe, it } from 'node:test'
import { renderFooter, recognizeFooter, withFooter, FOOTER_MARKER } from '../scripts/lib/attribution-footer.mjs'

describe('renderFooter', () => {
	it('contains the FOOTER_MARKER prefix', () => {
		assert.match(renderFooter('gaps', 'black'), new RegExp(FOOTER_MARKER.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')))
	})

	it('contains the dimension', () => {
		assert.match(renderFooter('gaps', 'black'), /dimension: gaps/)
	})

	it('contains the hat', () => {
		assert.match(renderFooter('gaps', 'black'), /hat: black/)
	})

	it('does not contain an em dash', () => {
		assert.doesNotMatch(renderFooter('ambiguity', 'black'), /—/)
	})
})

describe('withFooter', () => {
	it('appends the footer after a blank line', () => {
		const result = withFooter('comment body', 'gaps', 'black')
		assert.match(result, /comment body\n\n/)
		assert.match(result, /-- unic-spec-review/)
	})

	it('the appended footer is recognized by recognizeFooter', () => {
		const body = withFooter('some comment', 'testability', 'black')
		const r = recognizeFooter(body)
		assert.equal(r.recognized, true)
		assert.equal(r.dimension, 'testability')
		assert.equal(r.hat, 'black')
	})
})

describe('recognizeFooter', () => {
	it('recognizes a footer generated by renderFooter', () => {
		const footer = renderFooter('ambiguity', 'black')
		const r = recognizeFooter(footer)
		assert.equal(r.recognized, true)
		assert.equal(r.dimension, 'ambiguity')
		assert.equal(r.hat, 'black')
	})

	it('returns recognized=false for a plain human comment with no footer', () => {
		const r = recognizeFooter('This is a human comment.')
		assert.equal(r.recognized, false)
		assert.equal(r.dimension, undefined)
		assert.equal(r.hat, undefined)
	})

	it('recognizes a footer embedded in a full comment body', () => {
		const full = 'Title (critical)\n\nBody text.\n\n-- unic-spec-review | dimension: gaps | hat: black'
		const r = recognizeFooter(full)
		assert.equal(r.recognized, true)
	})

	it('is round-trip stable: withFooter output is always recognized', () => {
		const dims = ['gaps', 'ambiguity', 'testability', 'feasibility']
		const hats = ['black', 'green', 'yellow', 'red']
		for (const d of dims) {
			for (const h of hats) {
				const r = recognizeFooter(withFooter('body', d, h))
				assert.equal(r.recognized, true, `failed for dim=${d} hat=${h}`)
				assert.equal(r.dimension, d)
				assert.equal(r.hat, h)
			}
		}
	})
})
