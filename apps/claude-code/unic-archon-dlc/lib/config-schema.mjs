/**
 * Map a tracker type to its default CLI tool (MCP-first is expressed separately via `access.mcp`).
 * @param {unknown} tracker
 * @returns {string | null}
 */
function defaultTrackerCli(tracker) {
	if (tracker === 'github') return 'gh'
	if (tracker === 'ado') return 'az'
	if (tracker === 'jira') return 'jira'
	return null
}

/**
 * Plain-object test — arrays and null are NOT plain objects (they never deep-merge).
 * @param {unknown} v
 * @returns {v is Record<string, unknown>}
 */
function isPlainObject(v) {
	return typeof v === 'object' && v !== null && !Array.isArray(v)
}

/**
 * Recursively merge `source` over `target`. Plain objects merge key-by-key; every other value
 * (arrays, scalars, null) is replaced wholesale by `source`. Never mutates the inputs.
 * @param {Record<string, unknown>} target
 * @param {Record<string, unknown>} source
 * @returns {Record<string, unknown>}
 */
function deepMerge(target, source) {
	/** @type {Record<string, unknown>} */
	const out = { ...target }
	for (const [key, value] of Object.entries(source)) {
		const existing = out[key]
		out[key] = isPlainObject(existing) && isPlainObject(value) ? deepMerge(existing, value) : value
	}
	return out
}

/**
 * Merge answers over an existing config over the defaults: `DEFAULTS < existing < answers`.
 * Deep-merges nested objects (so partial answers never drop untouched keys) and is idempotent:
 * `mergeConfig(mergeConfig(a, b)) deep-equals mergeConfig(a, b)`.
 * @param {DlcConfig} [existing]
 * @param {Partial<DlcConfig>} [answers]
 * @returns {DlcConfig}
 */
export function mergeConfig(existing = {}, answers = {}) {
	return deepMerge(deepMerge(defaultConfig(), existing), answers)
}

/**
 * Detect a legacy flat ADR-0001 config (top-level `tracker` is a string, not an object).
 * @param {unknown} obj
 * @returns {boolean}
 */
export function isLegacyConfig(obj) {
	return isPlainObject(obj) && typeof obj.tracker === 'string'
}

/**
 * Translate a flat ADR-0001 JSON config into the rich nested shape. Preserves the file's own
 * `labels` verbatim (so hand-added label types such as `release` survive) rather than
 * regenerating from `getDefaultLabels`. Returns a PARTIAL — run it through `mergeConfig` to fill
 * defaults. Never touches or deletes the source file.
 * @param {Record<string, unknown>} flat
 * @returns {Partial<DlcConfig>}
 */
export function migrateLegacy(flat) {
	/** @type {Record<string, unknown>} */
	const project = {}
	if (flat.repo_layout !== undefined) project.repo_layout = flat.repo_layout
	if (flat.branching !== undefined) project.branching = flat.branching
	if (flat.pr_strategy !== undefined) project.pr_strategy = flat.pr_strategy

	/** @type {Record<string, unknown>} */
	const build = {}
	if (flat.tdd_mode !== undefined) build.tdd_mode = flat.tdd_mode
	if (flat.nyquist_validation !== undefined) build.nyquist_validation = flat.nyquist_validation
	if (flat.slopsquatting_gate !== undefined) build.slopsquatting_gate = flat.slopsquatting_gate
	if (flat.e2e_command !== undefined) build.e2e_command = flat.e2e_command
	if (flat.coverage_threshold !== undefined) build.coverage_threshold = flat.coverage_threshold

	/** @type {Partial<DlcConfig>} */
	const rich = {
		project,
		tracker: {
			type: flat.tracker,
			access: { mcp: null, cli: defaultTrackerCli(flat.tracker) },
			coords: {},
		},
		build,
	}
	if (flat.labels !== undefined) rich.classification = { labels: flat.labels }
	if (flat.model_profile !== undefined) rich.model_profile = flat.model_profile
	return rich
}

/**
 * Read a value at a dotted path (e.g. `tracker.type`) from a nested object.
 * @param {Record<string, unknown>} obj
 * @param {string} path
 * @returns {unknown}
 */
function getPath(obj, path) {
	/** @type {unknown} */
	let cursor = obj
	for (const segment of path.split('.')) {
		if (!isPlainObject(cursor)) return undefined
		cursor = cursor[segment]
	}
	return cursor
}

/**
 * Validate that every mandatory path is present and non-null.
 * @param {DlcConfig} config
 * @returns {{ ok: true, config: DlcConfig } | ConfigError}
 */
export function validateConfig(config) {
	const missing = MANDATORY_PATHS.filter((path) => {
		const value = getPath(config, path)
		return value === undefined || value === null || value === ''
	})
	if (missing.length > 0) {
		return { error: true, missing, message: `Missing mandatory config fields: ${missing.join(', ')}` }
	}
	return { ok: true, config }
}

/**
 * Parse a config file by extension: `.yaml`/`.yml` as YAML, `.json` as JSON, anything else tried
 * as JSON then YAML. Returns a structured error rather than throwing.
 * @param {string} path - absolute path to the config file
 * @returns {{ ok: true, config: DlcConfig } | ConfigError}
 */
export function loadConfig(path) {
	let raw
	try {
		raw = readFileSync(path, 'utf8')
	} catch (err) {
		return { error: true, missing: [], message: `Cannot read config at ${path}: ${/** @type {Error} */ (err).message}` }
	}
	const lower = path.toLowerCase()
	try {
		if (lower.endsWith('.json')) return { ok: true, config: JSON.parse(raw) }
		if (lower.endsWith('.yaml') || lower.endsWith('.yml')) return { ok: true, config: parseYaml(raw) }
		try {
			return { ok: true, config: JSON.parse(raw) }
		} catch {
			return { ok: true, config: parseYaml(raw) }
		}
	} catch (err) {
		return {
			error: true,
			missing: [],
			message: `Cannot parse config at ${path}: ${/** @type {Error} */ (err).message}`,
		}
	}
}

/**
 * Serialize a config to a YAML string. Validates first; returns a structured error on failure so
 * callers never write an invalid config to disk.
 * @param {DlcConfig} config
 * @returns {{ ok: true, yaml: string } | ConfigError}
 */
export function toYaml(config) {
	const validated = validateConfig(config)
	if ('error' in validated) return validated
	return { ok: true, yaml: stringifyYaml(config) }
}

/**
 * Detect repo layout the same way the ADR-0001 installer did: multi-context iff a root
 * `CONTEXT-MAP.md` exists. Callers pass the result into `answers.project.repo_layout`.
 * @param {string} projectDir
 * @returns {'single-context' | 'multi-context'}
 */
export function detectRepoLayout(projectDir) {
	return existsSync(join(projectDir, 'CONTEXT-MAP.md')) ? 'multi-context' : 'single-context'
}
