// @ts-check
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

/**
 * @typedef {Object} PrdSections
 * @property {string} problemStatement - Problem Statement section body
 * @property {string} solution - Solution section body
 * @property {string} userStories - User Stories section body
 * @property {string} implementationDecisions - Implementation Decisions section body
 * @property {string} testingDecisions - Testing Decisions section body
 * @property {string} outOfScope - Out of Scope section body
 * @property {string} furtherNotes - Further Notes section body
 */

/**
 * @typedef {Object} PrdValidationResult
 * @property {boolean} valid - true if all 7 headings are present
 * @property {string[]} missingSections - list of missing section headings
 */

const REQUIRED_HEADINGS = [
	'Problem Statement',
	'Solution',
	'User Stories',
	'Implementation Decisions',
	'Testing Decisions',
	'Out of Scope',
	'Further Notes',
]

/**
 * Write PRD.md for the given slug under docs/workflow/<slug>/PRD.md.
 * Creates the directory if absent. Overwrites any existing PRD.md.
 * @param {string} projectDir
 * @param {string} slug
 * @param {PrdSections} sections
 */
export function writePrd(projectDir, slug, sections) {
	const prdDir = join(projectDir, 'docs', 'workflow', slug)
	mkdirSync(prdDir, { recursive: true })

	const content = `# Product Requirements Document

_Generated by unic-archon-dlc plan workflow._

## Problem Statement

${sections.problemStatement}

## Solution

${sections.solution}

## User Stories

${sections.userStories}

## Implementation Decisions

${sections.implementationDecisions}

## Testing Decisions

${sections.testingDecisions}

## Out of Scope

${sections.outOfScope}

## Further Notes

${sections.furtherNotes}
`
	writeFileSync(join(prdDir, 'PRD.md'), content)
}

/**
 * Read PRD.md for the given slug.
 * Returns null if the file does not exist.
 * @param {string} projectDir
 * @param {string} slug
 * @returns {string | null}
 */
export function readPrd(projectDir, slug) {
	const prdPath = join(projectDir, 'docs', 'workflow', slug, 'PRD.md')
	if (!existsSync(prdPath)) return null
	return readFileSync(prdPath, 'utf8')
}

/**
 * Validate that a PRD.md string contains all 7 required section headings.
 * @param {string} content
 * @returns {PrdValidationResult}
 */
export function validatePrdSections(content) {
	const missingSections = REQUIRED_HEADINGS.filter((heading) => !content.includes(heading))
	return {
		valid: missingSections.length === 0,
		missingSections,
	}
}
