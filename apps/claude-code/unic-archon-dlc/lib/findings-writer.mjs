// @ts-check
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

/**
 * @typedef {Object} FindingsSections
 * @property {string} stack - Technology stack findings
 * @property {string} features - Key features findings
 * @property {string} architecture - Architecture findings
 * @property {string} pitfalls - Known pitfalls and gotchas
 * @property {string} brief - Integrated brief synthesizing all dimensions
 */

/**
 * Initialise the findings directory for a given slug.
 * Creates `docs/workflow/<slug>/` under projectDir if absent.
 * Safe to call multiple times — never destroys existing contents.
 * @param {string} projectDir
 * @param {string} slug
 * @returns {string} absolute path to the findings directory
 */
export function initFindingsDir(projectDir, slug) {
	const findingsDir = join(projectDir, 'docs', 'workflow', slug)
	mkdirSync(findingsDir, { recursive: true })
	return findingsDir
}

/**
 * Write findings.md into the given findings directory.
 * Sections: Stack, Features, Architecture, Pitfalls, Integrated Brief.
 * @param {string} findingsDir - path returned by initFindingsDir
 * @param {FindingsSections} sections
 */
export function writeFindingsMd(findingsDir, sections) {
	const content = `# Research Findings

_Generated by unic-archon-dlc explore workflow._

## Stack

${sections.stack}

## Features

${sections.features}

## Architecture

${sections.architecture}

## Pitfalls

${sections.pitfalls}

## Integrated Brief

${sections.brief}
`
	writeFileSync(join(findingsDir, 'findings.md'), content)
}

/**
 * Read findings.md from the given findings directory.
 * Returns null if the file does not exist.
 * @param {string} findingsDir
 * @returns {string | null}
 */
export function readFindingsMd(findingsDir) {
	const filePath = join(findingsDir, 'findings.md')
	if (!existsSync(filePath)) return null
	return readFileSync(filePath, 'utf8')
}
