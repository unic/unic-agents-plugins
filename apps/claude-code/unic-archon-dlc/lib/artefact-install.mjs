// @ts-check
import { cpSync, existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

/**
 * One tree-install engine, serving every artefact `/setup` writes as a declared install set (#294).
 *
 * Before this module, `installMethods` (`lib/methods-bundle.mjs`) was the only clean-replace path,
 * and it clean-replaces by DIRECTORY: it wipes `.archon/methods/` whole, because that tree is entirely
 * plugin-owned. The Box workflow YAMLs need a different rule — `.archon/workflows/` also holds a
 * Consumer's own workflows, so wiping the directory would delete unrelated work. This module holds
 * both rules behind one function, chosen per entry by `ownsWholeDir`.
 *
 * Name-scoped entries never delete by NAME MATCH against "the current set" alone — that would still
 * require knowing every name the plugin ever shipped. Instead a destination file is eligible for
 * removal only when (a) it is not in this run's set AND (b) it carries this module's own generated
 * header marker, proving `/setup` wrote it on a previous run. A Consumer's own file never carries that
 * marker and is therefore never touched, whatever its name.
 */

/** @typedef {(path: string, options: { recursive: boolean, force: boolean }) => void} RmFn */
/** @typedef {(from: string, to: string, options: { recursive: boolean }) => void} CpFn */
/** @typedef {(path: string) => boolean} ExistsFn */
/** @typedef {(path: string) => string[]} ReaddirFn */
/** @typedef {(path: string) => string} ReadFileFn */
/** @typedef {(path: string, contents: string) => void} WriteFileFn */
/** @typedef {(path: string) => void} MkdirFn */

/**
 * @typedef {Object} InstallItem
 * @property {string} name - destination-relative name: a file name, or (whole-dir entries) a directory name
 * @property {string} sourcePath - absolute path to copy/read from
 */

/**
 * @typedef {Object} InstallEntry
 * @property {string} name - label used only in the returned result, e.g. `'methods'`, `'workflows'`
 * @property {string} destDir - absolute destination directory
 * @property {readonly InstallItem[]} items - what this run installs, already resolved by the caller
 * @property {boolean} [ownsWholeDir] - `true` only for `.archon/methods`: wipes `destDir` first, then
 *   copies each item as a directory via `cpFn`. Default `false`: name-scoped clean-replace — see module doc.
 * @property {string} [header] - when set, every item is written as `${header}\n\n${sourceContents}`
 *   and the header is also what marks the file as ours for a future run's stale-deletion scan. Whole-dir
 *   entries never set this — they copy directories, not file content.
 */

/**
 * @typedef {Object} InstallDeps
 * @property {RmFn} [rmFn]
 * @property {CpFn} [cpFn]
 * @property {ExistsFn} [existsFn]
 * @property {ReaddirFn} [readdirFn]
 * @property {ReadFileFn} [readFileFn]
 * @property {WriteFileFn} [writeFileFn]
 * @property {MkdirFn} [mkdirFn]
 */

/**
 * @typedef {{ name: string, ok: true, installed: string[], deleted: string[], skipped: string[] } | { name: string, ok: false, installed: string[], deleted: string[], failed: string, error: Error }} InstallEntryResult
 */

/** The substring every header this module writes contains, and the only thing a stale-deletion scan checks for. */
export const GENERATED_HEADER_MARKER = 'AUTO-GENERATED by unic-archon-dlc'

/**
 * Build the two-line generated header a name-scoped entry prepends to every file it writes.
 * @param {string} pluginName
 * @param {string} version
 * @returns {string}
 */
export function buildGeneratedHeader(pluginName, version) {
	return (
		`# ${GENERATED_HEADER_MARKER} ${pluginName}@${version} — DO NOT EDIT BY HAND.\n` +
		`# Re-running /${pluginName}:setup replaces this file; hand edits are lost.`
	)
}

/**
 * List a source directory's entries as install items, skipping dotfiles (`.gitkeep` and the like).
 *
 * This is how a name-scoped entry discovers what to install **without** a fixed name list: the caller
 * passes the plugin's own copy of the tree, and whatever is in it this run is what ships this run.
 *
 * @param {Object} options
 * @param {string} options.sourceDir - absolute path to read
 * @param {ReaddirFn} [options.readdirFn]
 * @returns {InstallItem[]}
 */
export function discoverInstallItems({ sourceDir, readdirFn = (path) => readdirSync(path) }) {
	return readdirFn(sourceDir)
		.filter((name) => !name.startsWith('.'))
		.sort()
		.map((name) => ({ name, sourcePath: join(sourceDir, name) }))
}

/**
 * Install a declared set of artefact entries, whole-dir or name-scoped per entry.
 *
 * A whole-dir entry that fails partway stops at the failing item (mirroring the pre-#294
 * `installMethods` contract: the caller learns which items landed and which one failed, and a bare
 * re-run self-heals because the wipe runs again). A name-scoped entry never wipes anything, so there is
 * no partial-wipe state to protect against; an item-level failure there simply propagates as a throw.
 *
 * @param {Object} options
 * @param {readonly InstallEntry[]} options.entries
 * @param {RmFn} [options.rmFn]
 * @param {CpFn} [options.cpFn]
 * @param {ExistsFn} [options.existsFn]
 * @param {ReaddirFn} [options.readdirFn]
 * @param {ReadFileFn} [options.readFileFn]
 * @param {WriteFileFn} [options.writeFileFn]
 * @param {MkdirFn} [options.mkdirFn]
 * @returns {InstallEntryResult[]}
 */
export function installArtefacts({
	entries,
	rmFn = rmSync,
	cpFn = cpSync,
	existsFn = existsSync,
	readdirFn = (path) => readdirSync(path),
	readFileFn = (path) => readFileSync(path, 'utf8'),
	writeFileFn = writeFileSync,
	mkdirFn = (path) => {
		mkdirSync(path, { recursive: true })
	},
}) {
	/** @type {InstallEntryResult[]} */
	const results = []

	for (const entry of entries) {
		if (entry.ownsWholeDir) {
			rmFn(entry.destDir, { recursive: true, force: true })
			/** @type {string[]} */
			const installed = []
			let failure = null
			for (const item of entry.items) {
				try {
					cpFn(item.sourcePath, join(entry.destDir, item.name), { recursive: true })
				} catch (err) {
					failure = { failed: item.name, error: /** @type {Error} */ (err) }
					break
				}
				installed.push(item.name)
			}
			results.push(
				failure
					? { name: entry.name, ok: false, installed, deleted: [], ...failure }
					: { name: entry.name, ok: true, installed, deleted: [], skipped: [] }
			)
			continue
		}

		const currentNames = new Set(entry.items.map((item) => item.name))
		/** @type {string[]} */
		const deleted = []
		/** @type {string[]} */
		const skipped = []
		if (existsFn(entry.destDir)) {
			for (const existingName of readdirFn(entry.destDir)) {
				if (existingName.startsWith('.') || currentNames.has(existingName)) continue
				let contents
				try {
					contents = readFileFn(join(entry.destDir, existingName))
				} catch {
					skipped.push(existingName)
					continue
				}
				if (!contents.includes(GENERATED_HEADER_MARKER)) continue
				rmFn(join(entry.destDir, existingName), { recursive: true, force: true })
				deleted.push(existingName)
			}
		}

		// `cpSync` creates missing parents; `writeFileSync` does not. A Consumer that has never authored
		// a workflow has no `.archon/workflows/`, so the name-scoped path has to make one.
		if (entry.items.length > 0 && !existsFn(entry.destDir)) mkdirFn(entry.destDir)

		/** @type {string[]} */
		const installed = []
		for (const item of entry.items) {
			const contents = readFileFn(item.sourcePath)
			writeFileFn(join(entry.destDir, item.name), entry.header ? `${entry.header}\n\n${contents}` : contents)
			installed.push(item.name)
		}
		results.push({ name: entry.name, ok: true, installed, deleted, skipped })
	}

	return results
}
