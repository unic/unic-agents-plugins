// @ts-check
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const ROADMAP_BEGIN = '<!-- unic-archon-dlc:begin -->'
const ROADMAP_END = '<!-- unic-archon-dlc:end -->'

/**
 * @typedef {Object} HandoffSnapshot
 * @property {string} phase - current lifecycle phase (e.g. 'build', 'plan')
 * @property {Record<string, string[]>} openIssues - state label → issue titles
 * @property {string[]} blockers - blocker descriptions
 * @property {string[]} recentDecisions - ADR file basenames
 */

/**
 * Build the HANDOFF.md content from a workflow snapshot.
 * Returns a Markdown string with four sections: current phase, open issues,
 * blockers, and recent decisions.
 * @param {HandoffSnapshot} snapshot
 * @returns {string}
 */
export function buildHandoff(snapshot) {
	const issueLines = Object.entries(snapshot.openIssues)
		.flatMap(([state, titles]) => titles.map((t) => `  - [${state}] ${t}`))
		.join('\n')

	const blockerLines = snapshot.blockers.length ? snapshot.blockers.map((b) => `- ${b}`).join('\n') : '_No blockers._'

	const decisionLines = snapshot.recentDecisions.length
		? snapshot.recentDecisions.map((d) => `- ${d}`).join('\n')
		: '_No recent decisions._'

	return `# HANDOFF

_Generated by unic-archon-dlc triage workflow._

## Current Phase

**Phase:** ${snapshot.phase}

## Open Issues by State

${issueLines || '_No open issues._'}

## Blockers

${blockerLines}

## Recent Decisions

${decisionLines}
`
}

/**
 * Idempotent ROADMAP.md update using marker-delimited auto-generated region.
 * Human-written content outside the markers is preserved.
 * @param {string} projectDir
 * @param {string} phase - current lifecycle phase
 */
export function updateRoadmap(projectDir, phase) {
	const roadmapDir = join(projectDir, 'docs', 'workflow')
	mkdirSync(roadmapDir, { recursive: true })
	const roadmapPath = join(roadmapDir, 'ROADMAP.md')

	const timestamp = new Date().toISOString().slice(0, 10)
	const statusBlock = `**Last updated:** ${timestamp}  \n**Current phase:** ${phase}`
	const markerBlock = `${ROADMAP_BEGIN}\n${statusBlock}\n${ROADMAP_END}`

	if (!existsSync(roadmapPath)) {
		writeFileSync(roadmapPath, `# Project Roadmap\n\n${markerBlock}\n`)
		return
	}

	let content = readFileSync(roadmapPath, 'utf8')
	const beginIdx = content.indexOf(ROADMAP_BEGIN)
	const endIdx = content.indexOf(ROADMAP_END)

	if (beginIdx !== -1 && endIdx !== -1) {
		content = `${content.slice(0, beginIdx) + ROADMAP_BEGIN}\n${statusBlock}\n${content.slice(endIdx)}`
		writeFileSync(roadmapPath, content)
		return
	}

	// No markers yet — append the block
	const separator = content.endsWith('\n') ? '\n' : '\n\n'
	writeFileSync(roadmapPath, `${content}${separator}${markerBlock}\n`)
}
